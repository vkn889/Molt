// MARK: Clipboard

/// What you've copied: text, images and files. Passwords and anything an app marks as private
/// or temporary are never saved, nor anything copied in apps you ignore.
@MainActor final class ClipboardHistory: ObservableObject {
  struct Item: Codable, Identifiable, Equatable {
    enum Kind: String, Codable { case text, image, files }
    var id = UUID()
    var kind: Kind
    var text: String?
    /// The image's file name in the clipboard folder.
    var image: String?
    var files: [String]?
    var app: String?
    var date = Date()
    var pinned = false
    var title: String {
      switch kind {
      case .text: return text ?? ""
      case .image: return "Image"
      case .files: return (files ?? []).map { URL(fileURLWithPath: $0).lastPathComponent }.joined(separator: ", ")
      }
    }
  }
  @Published private(set) var items: [Item] = []
  /// Saving is paused until this time.
  @Published var pausedUntil: Date? = nil
  @Published var limit: Int { didSet { UserDefaults.standard.set(limit, forKey: "clipboardLimit"); trim() } }
  @Published var keepImages: Bool { didSet { UserDefaults.standard.set(keepImages, forKey: "clipboardImages") } }
  @Published var clearOnQuit: Bool { didSet { UserDefaults.standard.set(clearOnQuit, forKey: "clipboardClearOnQuit") } }
  /// Apps whose copies are never saved, by bundle identifier.
  @Published var ignored: [String] { didSet { UserDefaults.standard.set(ignored, forKey: "clipboardIgnored") } }
  static let passwordManagers = [
    "com.1password.1password", "com.agilebits.onepassword7", "com.bitwarden.desktop", "com.apple.keychainaccess",
    "com.lastpass.LastPass", "com.dashlane.dashlanephonefinal", "com.apple.Passwords", "in.sinew.Enpass-Desktop", "com.keepassxc.keepassxc",
  ]
  /// Pasteboard types apps use to say "don't keep this" (nspasteboard.org).
  static let privateTypes = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]
  private let folder: URL
  private var changeCount = NSPasteboard.general.changeCount
  private var timer: Timer?
  private var ownCopy = -1
  init(directory: URL) {
    folder = directory.appendingPathComponent("Clipboard")
    let defaults = UserDefaults.standard
    limit = defaults.object(forKey: "clipboardLimit") as? Int ?? 50
    keepImages = defaults.object(forKey: "clipboardImages") as? Bool ?? true
    clearOnQuit = defaults.object(forKey: "clipboardClearOnQuit") as? Bool ?? false
    ignored = defaults.stringArray(forKey: "clipboardIgnored") ?? Self.passwordManagers
    if let data = try? Data(contentsOf: folder.appendingPathComponent("history.json")),
      let saved = try? JSONDecoder().decode([Item].self, from: data)
    {
      items = saved
    }
  }
  /// Starts watching; checks for a new copy twice a second (reading a counter, which is cheap).
  func start() {
    guard timer == nil else { return }
    changeCount = NSPasteboard.general.changeCount
    timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in Task { @MainActor in self?.check() } }
    timer?.tolerance = 0.2
  }
  func stop() {
    timer?.invalidate()
    timer = nil
  }
  var paused: Bool { pausedUntil.map { $0 > Date() } ?? false }
  private func check() {
    let board = NSPasteboard.general
    guard board.changeCount != changeCount else { return }
    changeCount = board.changeCount
    guard board.changeCount != ownCopy, !paused, NotchPrefs.shared.has("clipboard") else { return }
    let types = board.types?.map(\.rawValue) ?? []
    if types.contains(where: Self.privateTypes.contains) { return }
    let app = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
    if let app, ignored.contains(app) { return }
    var item: Item?
    if let urls = board.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
      item = Item(kind: .files, files: urls.map(\.path), app: app)
    } else if let text = board.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
      item = Item(kind: .text, text: String(text.prefix(20_000)), app: app)
    } else if keepImages, let image = NSImage(pasteboard: board), let name = save(image) {
      item = Item(kind: .image, image: name, app: app)
    }
    guard let item else { return }
    // Copying the same thing again moves it to the top.
    if let index = items.firstIndex(where: { $0.kind == item.kind && $0.text == item.text && $0.files == item.files && item.kind != .image }) {
      var existing = items.remove(at: index)
      existing.date = Date()
      items.insert(existing, at: 0)
    } else {
      items.insert(item, at: 0)
    }
    trim()
    persist()
  }
  /// Puts an item back on the clipboard; `plain` drops formatting.
  func copy(_ item: Item, plain: Bool = false) {
    let board = NSPasteboard.general
    board.clearContents()
    switch item.kind {
    case .text: board.setString(item.text ?? "", forType: .string)
    case .image: if let image = image(item) { board.writeObjects([image]) }
    case .files: board.writeObjects((item.files ?? []).map { URL(fileURLWithPath: $0) as NSURL })
    }
    if plain, item.kind == .text { board.setString(item.text ?? "", forType: .string) }
    ownCopy = board.changeCount
  }
  func image(_ item: Item) -> NSImage? { item.image.flatMap { NSImage(contentsOf: folder.appendingPathComponent($0)) } }
  func togglePin(_ item: Item) {
    guard let index = items.firstIndex(of: item) else { return }
    items[index].pinned.toggle()
    persist()
  }
  func remove(_ item: Item) {
    items.removeAll { $0.id == item.id }
    if let image = item.image { try? FileManager.default.removeItem(at: folder.appendingPathComponent(image)) }
    persist()
  }
  /// Clears everything except what you pinned.
  func clear() {
    for item in items where !item.pinned { if let image = item.image { try? FileManager.default.removeItem(at: folder.appendingPathComponent(image)) } }
    items = items.filter(\.pinned)
    persist()
  }
  private func trim() {
    var unpinned = 0
    items = items.filter { item in
      if item.pinned { return true }
      unpinned += 1
      if unpinned > limit, let image = item.image { try? FileManager.default.removeItem(at: folder.appendingPathComponent(image)) }
      return unpinned <= limit
    }
  }
  /// Clipboard history can hold anything you copied, so it stays out of Time Machine backups.
  private func makeFolder() {
    try? FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
    var values = URLResourceValues()
    values.isExcludedFromBackup = true
    var url = folder
    try? url.setResourceValues(values)
  }
  private func save(_ image: NSImage) -> String? {
    makeFolder()
    // Kept small: at most 1200 points on the long side.
    let scale = min(1, 1200 / max(image.size.width, image.size.height, 1))
    let size = NSSize(width: image.size.width * scale, height: image.size.height * scale)
    let small = NSImage(size: size)
    small.lockFocus()
    image.draw(in: NSRect(origin: .zero, size: size))
    small.unlockFocus()
    guard let tiff = small.tiffRepresentation, let png = NSBitmapImageRep(data: tiff)?.representation(using: .png, properties: [:]) else { return nil }
    let name = UUID().uuidString + ".png"
    return (try? png.write(to: folder.appendingPathComponent(name), options: .atomic)) != nil ? name : nil
  }
  private func persist() {
    makeFolder()
    try? JSONEncoder().encode(items).write(to: folder.appendingPathComponent("history.json"), options: .atomic)
  }
}

// MARK: Timer, stopwatch and alarms

@MainActor final class TimerController: ObservableObject {
  struct Alarm: Codable, Identifiable, Equatable {
    var id = UUID()
    var hour: Int
    var minute: Int
    var label: String
    var on = true
    var lastFired: Date? = nil
    var time: String { String(format: "%d:%02d", hour, minute) }
  }
  /// When the timer ends, or how much was left when it was paused.
  @Published private(set) var ends: Date?
  @Published private(set) var pausedLeft: Double?
  @Published private(set) var length: Double = 300
  @Published private(set) var stopwatchStart: Date?
  @Published private(set) var stopwatchBanked: Double = 0
  @Published private(set) var laps: [Double] = []
  @Published var alarms: [Alarm] { didSet { save() } }
  var onAlert: (String, String) -> Void = { _, _ in }
  private var ticker: Timer?
  init() {
    alarms = (UserDefaults.standard.data(forKey: "alarms").flatMap { try? JSONDecoder().decode([Alarm].self, from: $0) }) ?? []
    ticker = Timer.scheduledTimer(withTimeInterval: 1, repeats: true) { [weak self] _ in Task { @MainActor in self?.tick() } }
    ticker?.tolerance = 0.3
  }
  var timerRunning: Bool { ends != nil }
  func left(at date: Date) -> Double { pausedLeft ?? ends.map { max(0, $0.timeIntervalSince(date)) } ?? length }
  func start(minutes: Double) {
    length = max(1, minutes * 60)
    ends = Date().addingTimeInterval(length)
    pausedLeft = nil
  }
  func pauseOrResume() {
    if let left = pausedLeft { ends = Date().addingTimeInterval(left); pausedLeft = nil }
    else if let ends { pausedLeft = max(0, ends.timeIntervalSinceNow); self.ends = nil }
  }
  func cancel() { ends = nil; pausedLeft = nil }
  var stopwatchRunning: Bool { stopwatchStart != nil }
  func stopwatch(at date: Date) -> Double { stopwatchBanked + (stopwatchStart.map { date.timeIntervalSince($0) } ?? 0) }
  func toggleStopwatch() {
    if let start = stopwatchStart { stopwatchBanked += Date().timeIntervalSince(start); stopwatchStart = nil } else { stopwatchStart = Date() }
  }
  func lap() { laps.insert(stopwatch(at: Date()), at: 0); laps = Array(laps.prefix(20)) }
  func resetStopwatch() { stopwatchStart = nil; stopwatchBanked = 0; laps = [] }
  func addAlarm(hour: Int, minute: Int, label: String) { alarms.append(Alarm(hour: hour, minute: minute, label: label)) }
  private func tick() {
    let now = Date()
    if let ends, ends <= now {
      self.ends = nil
      NSSound(named: "Glass")?.play()
      onAlert("Your \(Self.describe(length)) timer is done.", "timer")
    }
    let parts = Calendar.current.dateComponents([.hour, .minute], from: now)
    for index in alarms.indices where alarms[index].on && alarms[index].hour == parts.hour && alarms[index].minute == parts.minute {
      if let last = alarms[index].lastFired, now.timeIntervalSince(last) < 120 { continue }
      alarms[index].lastFired = now
      NSSound(named: "Sosumi")?.play()
      onAlert(alarms[index].label.isEmpty ? "It's \(alarms[index].time)." : alarms[index].label, "alarm")
    }
  }
  static func describe(_ seconds: Double) -> String {
    let minutes = Int(seconds / 60)
    return minutes >= 60 ? "\(minutes / 60)-hour" + (minutes % 60 > 0 ? " \(minutes % 60)-minute" : "") : "\(max(1, minutes))-minute"
  }
  private func save() { UserDefaults.standard.set(try? JSONEncoder().encode(alarms), forKey: "alarms") }
}

// MARK: Countdowns, habits and breaks

@MainActor final class DailyController: ObservableObject {
  @Published var countdowns: [Countdown] { didSet { save() } }
  @Published var habits: [Habit] { didSet { save() } }
  @Published var waterEvery: Int { didSet { UserDefaults.standard.set(waterEvery, forKey: "breakWater") } }
  @Published var stretchEvery: Int { didSet { UserDefaults.standard.set(stretchEvery, forKey: "breakStretch") } }
  @Published var breaksOn: Bool { didSet { UserDefaults.standard.set(breaksOn, forKey: "breaksOn"); started = Date() } }
  @Published private(set) var lastWater: Date?
  @Published private(set) var lastStretch: Date?
  @Published private(set) var waterToday = 0
  @Published private(set) var stretchToday = 0
  var onBreak: (String, String) -> Void = { _, _ in }
  var onHabitStreak: (Habit) -> Void = { _ in }
  private var started = Date()
  private var timer: Timer?
  private let url: URL
  struct Saved: Codable { var countdowns: [Countdown]; var habits: [Habit] }
  init(directory: URL) {
    url = directory.appendingPathComponent("daily.json")
    let saved = (try? Data(contentsOf: url)).flatMap { try? JSONDecoder().decode(Saved.self, from: $0) }
    countdowns = saved?.countdowns ?? []
    habits = saved?.habits ?? [Habit(title: "Drink water", symbol: "drop.fill"), Habit(title: "Move", symbol: "figure.walk")]
    let defaults = UserDefaults.standard
    waterEvery = defaults.object(forKey: "breakWater") as? Int ?? 45
    stretchEvery = defaults.object(forKey: "breakStretch") as? Int ?? 60
    breaksOn = defaults.object(forKey: "breaksOn") as? Bool ?? false
    timer = Timer.scheduledTimer(withTimeInterval: 30, repeats: true) { [weak self] _ in Task { @MainActor in self?.check() } }
    timer?.tolerance = 10
  }
  func nextWater(at now: Date) -> Date { Breaks.next(every: waterEvery, last: lastWater, start: started, now: now) }
  func nextStretch(at now: Date) -> Date { Breaks.next(every: stretchEvery, last: lastStretch, start: started, now: now) }
  func tookWater() { lastWater = Date(); waterToday += 1 }
  func stretched() { lastStretch = Date(); stretchToday += 1 }
  private var reminded: Set<String> = []
  private func check() {
    let now = Date()
    if !Calendar.current.isDate(now, inSameDayAs: started) && waterToday + stretchToday > 0 && Calendar.current.component(.hour, from: now) < 5 {
      waterToday = 0; stretchToday = 0
    }
    guard breaksOn, NotchPrefs.shared.has("focus") else { return }
    let water = nextWater(at: now), stretch = nextStretch(at: now)
    if water <= now, reminded.insert("w\(Int(water.timeIntervalSince1970))").inserted {
      onBreak("Time for some water. I'll have some too.", "drop.fill")
    }
    if stretch <= now, reminded.insert("s\(Int(stretch.timeIntervalSince1970))").inserted {
      onBreak("Stand up and stretch for a minute. Let's go!", "figure.walk")
    }
  }
  func toggle(_ habit: Habit) {
    guard let index = habits.firstIndex(where: { $0.id == habit.id }) else { return }
    habits[index].toggle(on: Date())
    if habits[index].isDone(on: Date()) { onHabitStreak(habits[index]) }
  }
  private func save() {
    try? JSONEncoder().encode(Saved(countdowns: countdowns, habits: habits)).write(to: url, options: .atomic)
  }
}

// MARK: Apple Reminders

@MainActor final class RemindersController: ObservableObject {
  @Published private(set) var reminders: [EKReminder] = []
  @Published private(set) var lists: [EKCalendar] = []
  @Published private(set) var allowed = EKEventStore.authorizationStatus(for: .reminder) == .authorized || RemindersController.fullAccess
  @Published var list: String { didSet { UserDefaults.standard.set(list, forKey: "remindersList"); refresh() } }
  private let store = EKEventStore()
  private var observer: NSObjectProtocol?
  private static var fullAccess: Bool {
    if #available(macOS 14.0, *) { return EKEventStore.authorizationStatus(for: .reminder) == .fullAccess }
    return false
  }
  init() {
    list = UserDefaults.standard.string(forKey: "remindersList") ?? ""
    observer = NotificationCenter.default.addObserver(forName: .EKEventStoreChanged, object: store, queue: .main) { [weak self] _ in
      Task { @MainActor in self?.refresh() }
    }
  }
  func requestAccess() {
    let done: (Bool) -> Void = { granted in Task { @MainActor in self.allowed = granted; self.refresh() } }
    if #available(macOS 14.0, *) {
      store.requestFullAccessToReminders { granted, _ in done(granted) }
    } else {
      store.requestAccess(to: .reminder) { granted, _ in done(granted) }
    }
  }
  func refresh() {
    guard allowed else { return }
    lists = store.calendars(for: .reminder)
    let chosen = lists.filter { list.isEmpty || $0.calendarIdentifier == list }
    let predicate = store.predicateForIncompleteReminders(withDueDateStarting: nil, ending: nil, calendars: chosen.isEmpty ? nil : chosen)
    store.fetchReminders(matching: predicate) { [weak self] found in
      let sorted = (found ?? []).sorted { ($0.dueDateComponents?.date ?? .distantFuture) < ($1.dueDateComponents?.date ?? .distantFuture) }
      Task { @MainActor in self?.reminders = Array(sorted.prefix(20)) }
    }
  }
  func complete(_ reminder: EKReminder) {
    reminder.isCompleted = true
    try? store.save(reminder, commit: true)
    reminders.removeAll { $0.calendarItemIdentifier == reminder.calendarItemIdentifier }
  }
  func add(_ title: String) {
    guard allowed, let calendar = lists.first(where: { $0.calendarIdentifier == list }) ?? store.defaultCalendarForNewReminders() else { return }
    let reminder = EKReminder(eventStore: store)
    reminder.title = String(title.prefix(200))
    reminder.calendar = calendar
    try? store.save(reminder, commit: true)
    refresh()
  }
}

// MARK: Device batteries

/// Batteries of things connected to the Mac: Magic Keyboard, Mouse and Trackpad, and AirPods.
@MainActor final class DeviceBatteries: ObservableObject {
  struct Device: Identifiable, Equatable { var id: String; var name: String; var percent: Int; var symbol: String }
  @Published private(set) var devices: [Device] = []
  @Published private(set) var loading = false
  private var updated = Date.distantPast
  func refresh(force: Bool = false) {
    guard !loading, force || Date().timeIntervalSince(updated) > 120 else { return }
    loading = true
    // AirPods come from Bluetooth, which needs your permission first.
    let bluetooth = Bluetooth.allowed
    Task.detached(priority: .utility) {
      let found = Self.hid() + (bluetooth ? Self.airpods() : [])
      await MainActor.run {
        self.devices = found
        self.loading = false
        self.updated = Date()
      }
    }
  }
  nonisolated static func symbol(_ name: String) -> String {
    let lower = name.lowercased()
    if lower.contains("airpods max") { return "airpodsmax" }
    if lower.contains("airpods pro") { return "airpodspro" }
    if lower.contains("airpods") { return "airpods" }
    if lower.contains("keyboard") { return "keyboard" }
    if lower.contains("trackpad") { return "rectangle.and.hand.point.up.left" }
    if lower.contains("mouse") { return "magicmouse" }
    return "battery.75"
  }
  /// Magic accessories report their battery through IOKit.
  nonisolated static func hid() -> [Device] {
    var devices: [Device] = []
    var iterator: io_iterator_t = 0
    guard IOServiceGetMatchingServices(kIOMainPortDefault, IOServiceMatching("AppleDeviceManagementHIDEventService"), &iterator) == KERN_SUCCESS else { return [] }
    defer { IOObjectRelease(iterator) }
    while case let service = IOIteratorNext(iterator), service != 0 {
      defer { IOObjectRelease(service) }
      let percent = IORegistryEntryCreateCFProperty(service, "BatteryPercent" as CFString, kCFAllocatorDefault, 0)?.takeRetainedValue() as? Int
      let name = IORegistryEntryCreateCFProperty(service, "Product" as CFString, kCFAllocatorDefault, 0)?.takeRetainedValue() as? String
      if let percent, let name, !devices.contains(where: { $0.name == name }) {
        devices.append(Device(id: name, name: name, percent: percent, symbol: symbol(name)))
      }
    }
    return devices
  }
  /// AirPods and other Bluetooth headphones, from System Information.
  nonisolated static func airpods() -> [Device] {
    let process = Process()
    process.executableURL = URL(fileURLWithPath: "/usr/sbin/system_profiler")
    process.arguments = ["SPBluetoothDataType", "-json", "-detailLevel", "basic"]
    let pipe = Pipe()
    process.standardOutput = pipe
    process.standardError = FileHandle.nullDevice
    guard (try? process.run()) != nil else { return [] }
    let data = pipe.fileHandleForReading.readDataToEndOfFile()
    process.waitUntilExit()
    guard let json = try? JSONSerialization.jsonObject(with: data) as? [String: Any],
      let sections = json["SPBluetoothDataType"] as? [[String: Any]]
    else { return [] }
    var devices: [Device] = []
    for section in sections {
      for entry in section["device_connected"] as? [[String: Any]] ?? [] {
        for (name, value) in entry {
          guard let info = value as? [String: Any] else { continue }
          let levels = ["device_batteryLevelLeft", "device_batteryLevelRight", "device_batteryLevelMain", "device_batteryLevel"]
            .compactMap { (info[$0] as? String).flatMap { Int($0.replacingOccurrences(of: "%", with: "")) } }
          if let lowest = levels.min() { devices.append(Device(id: name, name: name, percent: lowest, symbol: symbol(name))) }
          if let box = (info["device_batteryLevelCase"] as? String).flatMap({ Int($0.replacingOccurrences(of: "%", with: "")) }) {
            devices.append(Device(id: name + " case", name: "\(name) case", percent: box, symbol: "airpods.chargingcase"))
          }
        }
      }
    }
    return devices
  }
}

// MARK: Network

@MainActor final class NetworkMonitor: ObservableObject {
  @Published private(set) var down: Double = 0
  @Published private(set) var up: Double = 0
  @Published private(set) var wifi: String?
  @Published private(set) var localIP: String?
  @Published private(set) var publicIP: String?
  @Published private(set) var history: [Double] = []
  private var last: (Date, UInt64, UInt64)?
  private var timer: Timer?
  var active = false {
    didSet {
      guard active != oldValue else { return }
      timer?.invalidate()
      timer = nil
      guard active else { return }
      sample()
      timer = Timer.scheduledTimer(withTimeInterval: 2, repeats: true) { [weak self] _ in Task { @MainActor in self?.sample() } }
    }
  }
  private func sample() {
    let (received, sent, ip) = Self.counters()
    let now = Date()
    if let (date, r0, s0) = last {
      let seconds = max(0.5, now.timeIntervalSince(date))
      // Counters wrap at 4 GB; a negative step means one did.
      down = received >= r0 ? Double(received - r0) / seconds : 0
      up = sent >= s0 ? Double(sent - s0) / seconds : 0
      history = Array((history + [down]).suffix(40))
    }
    last = (now, received, sent)
    localIP = ip
    wifi = CWWiFiClient.shared().interface()?.ssid()
  }
  /// Bytes in and out on every active network interface, and the main one's IPv4 address.
  nonisolated static func counters() -> (UInt64, UInt64, String?) {
    var pointer: UnsafeMutablePointer<ifaddrs>?
    guard getifaddrs(&pointer) == 0, let first = pointer else { return (0, 0, nil) }
    defer { freeifaddrs(pointer) }
    var received: UInt64 = 0, sent: UInt64 = 0
    var ip: String?
    for address in sequence(first: first, next: { $0.pointee.ifa_next }) {
      let name = String(cString: address.pointee.ifa_name)
      guard name.hasPrefix("en") || name.hasPrefix("utun") || name.hasPrefix("pdp_ip"), let socket = address.pointee.ifa_addr else { continue }
      if socket.pointee.sa_family == UInt8(AF_LINK), let data = address.pointee.ifa_data?.assumingMemoryBound(to: if_data.self) {
        received += UInt64(data.pointee.ifi_ibytes)
        sent += UInt64(data.pointee.ifi_obytes)
      } else if socket.pointee.sa_family == UInt8(AF_INET), ip == nil, name.hasPrefix("en") {
        var host = [CChar](repeating: 0, count: Int(NI_MAXHOST))
        if getnameinfo(socket, socklen_t(socket.pointee.sa_len), &host, socklen_t(host.count), nil, 0, NI_NUMERICHOST) == 0 { ip = String(cString: host) }
      }
    }
    return (received, sent, ip)
  }
  /// Your address on the internet, fetched only when you ask.
  func lookUpPublicIP() {
    Task {
      var request = URLRequest(url: URL(string: "https://api.ipify.org")!)
      request.timeoutInterval = 8
      if let (data, _) = try? await URLSession.shared.data(for: request) { publicIP = String(decoding: data.prefix(64), as: UTF8.self) }
    }
  }
  static func rate(_ bytes: Double) -> String {
    let bits = bytes * 8
    if bits >= 1_000_000 { return String(format: "%.1f Mb/s", bits / 1_000_000) }
    if bits >= 1000 { return String(format: "%.0f kb/s", bits / 1000) }
    return String(format: "%.0f b/s", bits)
  }
}

// MARK: System graph

@MainActor final class SystemGraph: ObservableObject {
  @Published private(set) var cpu: [Double] = []
  @Published private(set) var memory: [Double] = []
  private let monitor = SystemHealthMonitor()
  private var timer: Timer?
  var active = false {
    didSet {
      guard active != oldValue else { return }
      timer?.invalidate()
      timer = nil
      guard active else { return }
      sample()
      timer = Timer.scheduledTimer(withTimeInterval: 2, repeats: true) { [weak self] _ in Task { @MainActor in self?.sample() } }
    }
  }
  private func sample() {
    let values = monitor.currentSnapshot().values
    cpu = Array((cpu + [values["cpuLoad"] ?? 0]).suffix(60))
    memory = Array((memory + [values["memoryUsed"] ?? 0]).suffix(60))
  }
}

// MARK: Sound output

@MainActor final class AudioOutputs: ObservableObject {
  struct Device: Identifiable, Equatable { var id: AudioDeviceID; var name: String }
  @Published private(set) var devices: [Device] = []
  @Published private(set) var current: AudioDeviceID = 0
  @Published var volume: Float = 0
  func refresh() {
    devices = Self.all().filter { Self.streams($0, scope: kAudioObjectPropertyScopeOutput) }.map { Device(id: $0, name: Self.name($0)) }
    current = Self.defaultOutput()
    volume = Self.volume(current) ?? 0
  }
  func choose(_ device: Device) {
    var id = device.id
    var address = AudioObjectPropertyAddress(mSelector: kAudioHardwarePropertyDefaultOutputDevice, mScope: kAudioObjectPropertyScopeGlobal, mElement: kAudioObjectPropertyElementMain)
    AudioObjectSetPropertyData(AudioObjectID(kAudioObjectSystemObject), &address, 0, nil, UInt32(MemoryLayout<AudioDeviceID>.size), &id)
    refresh()
  }
  func setVolume(_ value: Float) {
    volume = value
    var level = min(1, max(0, value))
    var address = AudioObjectPropertyAddress(mSelector: kAudioHardwareServiceDeviceProperty_VirtualMainVolume, mScope: kAudioObjectPropertyScopeOutput, mElement: kAudioObjectPropertyElementMain)
    AudioObjectSetPropertyData(current, &address, 0, nil, UInt32(MemoryLayout<Float32>.size), &level)
  }
  nonisolated static func all() -> [AudioDeviceID] {
    var address = AudioObjectPropertyAddress(mSelector: kAudioHardwarePropertyDevices, mScope: kAudioObjectPropertyScopeGlobal, mElement: kAudioObjectPropertyElementMain)
    var size: UInt32 = 0
    guard AudioObjectGetPropertyDataSize(AudioObjectID(kAudioObjectSystemObject), &address, 0, nil, &size) == noErr else { return [] }
    var ids = [AudioDeviceID](repeating: 0, count: Int(size) / MemoryLayout<AudioDeviceID>.size)
    guard AudioObjectGetPropertyData(AudioObjectID(kAudioObjectSystemObject), &address, 0, nil, &size, &ids) == noErr else { return [] }
    return ids
  }
  nonisolated static func streams(_ id: AudioDeviceID, scope: AudioObjectPropertyScope) -> Bool {
    var address = AudioObjectPropertyAddress(mSelector: kAudioDevicePropertyStreams, mScope: scope, mElement: kAudioObjectPropertyElementMain)
    var size: UInt32 = 0
    return AudioObjectGetPropertyDataSize(id, &address, 0, nil, &size) == noErr && size > 0
  }
  nonisolated static func name(_ id: AudioDeviceID) -> String {
    var address = AudioObjectPropertyAddress(mSelector: kAudioObjectPropertyName, mScope: kAudioObjectPropertyScopeGlobal, mElement: kAudioObjectPropertyElementMain)
    var name: Unmanaged<CFString>?
    var size = UInt32(MemoryLayout<Unmanaged<CFString>?>.size)
    guard AudioObjectGetPropertyData(id, &address, 0, nil, &size, &name) == noErr, let value = name?.takeRetainedValue() else { return "Output" }
    return value as String
  }
  nonisolated static func defaultOutput() -> AudioDeviceID {
    var address = AudioObjectPropertyAddress(mSelector: kAudioHardwarePropertyDefaultOutputDevice, mScope: kAudioObjectPropertyScopeGlobal, mElement: kAudioObjectPropertyElementMain)
    var id: AudioDeviceID = 0
    var size = UInt32(MemoryLayout<AudioDeviceID>.size)
    AudioObjectGetPropertyData(AudioObjectID(kAudioObjectSystemObject), &address, 0, nil, &size, &id)
    return id
  }
  nonisolated static func volume(_ id: AudioDeviceID) -> Float? {
    var address = AudioObjectPropertyAddress(mSelector: kAudioHardwareServiceDeviceProperty_VirtualMainVolume, mScope: kAudioObjectPropertyScopeOutput, mElement: kAudioObjectPropertyElementMain)
    var level: Float32 = 0
    var size = UInt32(MemoryLayout<Float32>.size)
    return AudioObjectGetPropertyData(id, &address, 0, nil, &size, &level) == noErr ? level : nil
  }
  /// Whether any app is using a microphone right now.
  nonisolated static func microphoneInUse() -> Bool {
    all().filter { streams($0, scope: kAudioObjectPropertyScopeInput) }.contains { id in
      var address = AudioObjectPropertyAddress(mSelector: kAudioDevicePropertyDeviceIsRunningSomewhere, mScope: kAudioObjectPropertyScopeGlobal, mElement: kAudioObjectPropertyElementMain)
      var running: UInt32 = 0
      var size = UInt32(MemoryLayout<UInt32>.size)
      return AudioObjectGetPropertyData(id, &address, 0, nil, &size, &running) == noErr && running != 0
    }
  }
}

// MARK: Microphone and camera in use

@MainActor final class MediaInUse: ObservableObject {
  @Published private(set) var camera = false
  @Published private(set) var microphone = false
  private var timer: Timer?
  var active = false {
    didSet {
      guard active != oldValue else { return }
      timer?.invalidate()
      timer = nil
      guard active else { return }
      check()
      timer = Timer.scheduledTimer(withTimeInterval: 2, repeats: true) { [weak self] _ in Task { @MainActor in self?.check() } }
    }
  }
  private func check() {
    Task.detached(priority: .utility) {
      let camera = Self.cameraInUse(), microphone = AudioOutputs.microphoneInUse()
      await MainActor.run {
        self.camera = camera
        self.microphone = microphone
      }
    }
  }
  nonisolated static func cameraInUse() -> Bool {
    var address = CMIOObjectPropertyAddress(mSelector: CMIOObjectPropertySelector(kCMIOHardwarePropertyDevices), mScope: CMIOObjectPropertyScope(kCMIOObjectPropertyScopeGlobal), mElement: CMIOObjectPropertyElement(kCMIOObjectPropertyElementMain))
    var size: UInt32 = 0
    guard CMIOObjectGetPropertyDataSize(CMIOObjectID(kCMIOObjectSystemObject), &address, 0, nil, &size) == noErr else { return false }
    var ids = [CMIOObjectID](repeating: 0, count: Int(size) / MemoryLayout<CMIOObjectID>.size)
    var used: UInt32 = 0
    guard CMIOObjectGetPropertyData(CMIOObjectID(kCMIOObjectSystemObject), &address, 0, nil, size, &used, &ids) == noErr else { return false }
    return ids.contains { id in
      var running = CMIOObjectPropertyAddress(mSelector: CMIOObjectPropertySelector(kCMIODevicePropertyDeviceIsRunningSomewhere), mScope: CMIOObjectPropertyScope(kCMIOObjectPropertyScopeWildcard), mElement: CMIOObjectPropertyElement(kCMIOObjectPropertyElementWildcard))
      var value: UInt32 = 0
      var got: UInt32 = 0
      return CMIOObjectGetPropertyData(id, &running, 0, nil, UInt32(MemoryLayout<UInt32>.size), &got, &value) == noErr && value != 0
    }
  }
}

// MARK: Recent files and screenshots

@MainActor final class RecentFiles: ObservableObject {
  @Published private(set) var files: [URL] = []
  private var query: NSMetadataQuery?
  private var observer: NSObjectProtocol?
  func refresh() {
    query?.stop()
    let query = NSMetadataQuery()
    query.searchScopes = [NSMetadataQueryUserHomeScope]
    let since = Date().addingTimeInterval(-3 * 86400) as NSDate
    query.predicate = NSPredicate(format: "kMDItemLastUsedDate >= %@ AND kMDItemContentTypeTree != 'com.apple.application' AND kMDItemContentTypeTree != 'public.folder'", since)
    query.sortDescriptors = [NSSortDescriptor(key: "kMDItemLastUsedDate", ascending: false)]
    observer.map(NotificationCenter.default.removeObserver)
    observer = NotificationCenter.default.addObserver(forName: .NSMetadataQueryDidFinishGathering, object: query, queue: .main) { [weak self] _ in
      Task { @MainActor in
        guard let self, let query = self.query else { return }
        query.disableUpdates()
        let found = (0..<min(query.resultCount, 30)).compactMap { (query.result(at: $0) as? NSMetadataItem)?.value(forAttribute: NSMetadataItemPathKey) as? String }
        self.files = Array(found.map(URL.init(fileURLWithPath:)).filter { !$0.path.contains("/Library/") && !$0.lastPathComponent.hasPrefix(".") }.prefix(8))
        query.stop()
      }
    }
    self.query = query
    query.start()
  }
  /// Your latest screenshots and screen recordings, wherever macOS saves them.
  static func screenshots() async -> [URL] {
    await Task.detached(priority: .utility) { () -> [URL] in
      let saved = UserDefaults(suiteName: "com.apple.screencapture")?.string(forKey: "location").map { ($0 as NSString).expandingTildeInPath }
      let folder = URL(fileURLWithPath: saved ?? (FileManager.default.homeDirectoryForCurrentUser.appendingPathComponent("Desktop").path))
      let keys: [URLResourceKey] = [.creationDateKey]
      let items = (try? FileManager.default.contentsOfDirectory(at: folder, includingPropertiesForKeys: keys, options: [.skipsHiddenFiles])) ?? []
      let shots = items.filter { url in
        let name = url.lastPathComponent
        return ["Screenshot", "Screen Shot", "Screen Recording", "CleanShot", "Molt Recording"].contains { name.hasPrefix($0) }
      }
      func date(_ url: URL) -> Date { (try? url.resourceValues(forKeys: Set(keys)))?.creationDate ?? .distantPast }
      return Array(shots.sorted { date($0) > date($1) }.prefix(8))
    }.value
  }
}
